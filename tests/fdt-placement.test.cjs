const { test } = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')
const load = require('./helpers/load-typescript.cjs')
const { placeFdt, mountingPole, projectFdts } = load(path.resolve(__dirname, '../lib/fdt-placement.ts'))
const { emptyAssignmentProject } = load(path.resolve(__dirname, '../lib/manual-assignments.ts'))
const { saveAssignmentProject, loadAssignmentProject } = load(path.resolve(__dirname, '../lib/project-storage.ts'))
const point = (id, category, x) => ({ id, name: id, category, file: 'test', kind: 'Point', coords: [-6.9, x], geometry: { type: 'Point', coordinates: [x, -6.9] } })
const base = () => ({ ...emptyAssignmentProject(), features: [point('T1', 'Tiang', 107), point('T2', 'Tiang', 107.001), point('H', 'Rumah', 107.002)] })
test('preview/cancel leave project unchanged; confirmed create uses exact pole and does not duplicate', () => {
 const p = base(), before = JSON.stringify(p)
 assert.equal(projectFdts(p).length, 0)
 assert.equal(JSON.stringify(p), before)
 const next = placeFdt(p, null, 'T1', 'fdt-1')
 assert.equal(projectFdts(next).length, 1)
 assert.equal(mountingPole(next, projectFdts(next)[0]), 'T1')
 assert.deepEqual(projectFdts(next)[0].geometry, p.features[0].geometry)
 assert.throws(() => placeFdt(next, null, 'T1', 'fdt-1'))
 assert.deepEqual(next.distributionStaleFdtIds, ['fdt-1'])
 assert.equal(next.simulation, p.simulation)
 assert.equal(JSON.stringify(p), before)
})
test('move targets exact device, retains metadata and allocations, source selection rejects', () => {
 let p = placeFdt(base(), null, 'T1', 'fdt-1')
 p.features.push({ ...point('fdt-2', 'FDT', 107.004), description: 'configuration preserved' })
 const next = placeFdt(p, 'fdt-2', 'T2', '')
 assert.equal(next.features.find(f => f.id === 'fdt-2').description, 'configuration preserved')
 assert.deepEqual(next.features.find(f => f.id === 'fdt-1'), p.features.find(f => f.id === 'fdt-1'))
 assert.equal(next.decisions, p.decisions)
 assert.equal(next.plan, p.plan)
 assert.equal(next.simulation, p.simulation)
 assert.throws(() => placeFdt(next, 'fdt-2', 'T2', ''), /saat ini/)
 assert.throws(() => placeFdt(next, 'missing', 'T2', ''), /tidak tersedia/)
 assert.throws(() => placeFdt(next, 'fdt-2', 'missing', ''), /tidak tersedia/)
})
test('save refresh preserves FDT mounting, unique ID and distribution stale status', () => {
 const p = placeFdt(placeFdt(base(), null, 'T1', 'fdt-1'), 'fdt-1', 'T2', '')
 let saved = null
 const storage = { setItem: (_, value) => { saved = value }, getItem: () => saved }
 saveAssignmentProject(storage, p, { maxDropLengthMeters: 60 })
 const restored = loadAssignmentProject(storage).project
 assert.equal(projectFdts(restored).length, 1)
 assert.equal(mountingPole(restored, projectFdts(restored)[0]), 'T2')
 assert.deepEqual(restored.distributionStaleFdtIds, ['fdt-1'])
 assert.deepEqual(restored.features, p.features)
 const before = JSON.stringify(p)
 assert.throws(() => saveAssignmentProject({ setItem: () => { throw new Error('quota') } }, placeFdt(p, 'fdt-1', 'T1', ''), { maxDropLengthMeters: 60 }))
 assert.equal(JSON.stringify(p), before)
})
